type Material struct {
	Label  string `json:"label"`
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}
type ExportIntent struct {
	Schema       int        `json:"schema"`
	ControllerID string     `json:"controller_id"`
	OperationID  string     `json:"operation_id"`
	PlanSHA256   string     `json:"plan_sha256"`
	Materials    []Material `json:"materials"`
}
type ExportReport struct {
	Schema         int    `json:"schema"`
	ControllerID   string `json:"controller_id"`
	OperationID    string `json:"operation_id"`
	ArchiveSHA256  string `json:"archive_sha256"`
	ArchiveBytes   int64  `json:"archive_bytes"`
	DatabaseRows   int64  `json:"database_rows"`
	SourceReadOnly bool   `json:"source_readonly"`
	SourceIsolated bool   `json:"source_isolated"`
	MigrationReady bool   `json:"migration_ready"`
}

func digestBytes(raw []byte) string { sum := sha256.Sum256(raw); return hex.EncodeToString(sum[:]) }
func strictRecord(raw []byte, target any) bool {
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	return d.Decode(target) == nil && d.Decode(new(any)) == io.EOF
}

type quotaWriter struct {
	writer io.Writer
	left   *int64
}

func (w quotaWriter) Write(p []byte) (int, error) {
	if int64(len(p)) > *w.left {
		return 0, ErrInvalid
	}
	n, e := w.writer.Write(p)
	*w.left -= int64(n)
	return n, e
}

// ExportSealedSource may only run while the caller owns the runtime control
// lock and the coordinator owns host-operation.lock. It never unseals a source,
// reconnects a node, changes database rows or overwrites an existing backup.
func ExportSealedSource(ctx context.Context, config control.Config, operation string) (ExportReport, error) {
	if os.Geteuid() != 0 || !controllerID.MatchString(config.ControllerID) || !operationID.MatchString(operation) {
		return ExportReport{}, ErrInvalid
	}
	root := filepath.Join("/var/lib/aster-controller", config.ControllerID)
	dir := filepath.Join(root, "host-migrations", operation)
	read := func(path string, maximum int64) ([]byte, error) { return control.ReadProtected(path, true, maximum) }
	plan, e := read(filepath.Join(dir, "plan.json"), 256<<10)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	seal, e := read(filepath.Join(root, "host-migration.json"), 4096)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	var marker struct {
		Schema       int    `json:"schema"`
		ControllerID string `json:"controller_id"`
		OperationID  string `json:"operation_id"`
		PlanSHA256   string `json:"plan_sha256"`
	}
	if !strictRecord(seal, &marker) || marker.Schema != 1 || marker.ControllerID != config.ControllerID || marker.OperationID != operation || marker.PlanSHA256 != digestBytes(plan) {
		return ExportReport{}, ErrInvalid
	}
	started, e := read(filepath.Join(dir, "export-started.json"), 256<<10)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	var intent ExportIntent
	if !strictRecord(started, &intent) || intent.Schema != 1 || intent.ControllerID != config.ControllerID || intent.OperationID != operation || intent.PlanSHA256 != marker.PlanSHA256 {
		return ExportReport{}, ErrInvalid
	}
	// Host receipts are generated by the trusted coordinator, not supplied by
	// archive input. Bind their actual bytes to the fixed installed source.
	var p struct {
		Schema   int               `json:"schema"`
		Identity map[string]string `json:"identity"`
		Units    []json.RawMessage `json:"units"`
	}
	if !strictRecord(plan, &p) || p.Schema != 1 || p.Identity["controller_id"] != config.ControllerID || !sourceSHA.MatchString(p.Identity["source_commit"]) {
		return ExportReport{}, ErrInvalid
	}
	isolated, e := read(filepath.Join(dir, "isolated.json"), 256<<10)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	var receipt struct {
		Schema      int               `json:"schema"`
		OperationID string            `json:"operation_id"`
		Identity    map[string]string `json:"identity"`
	}
	if !strictRecord(isolated, &receipt) || receipt.Schema != 1 || receipt.OperationID != operation {
		return ExportReport{}, ErrInvalid
	}
	a, _ := json.Marshal(receipt.Identity)
	b, _ := json.Marshal(p.Identity)
	if !bytes.Equal(a, b) {
		return ExportReport{}, ErrInvalid
	}
	configRaw, e := read("/etc/aster-controller/config.json", 65536)
	if e != nil || digestBytes(configRaw) != p.Identity["configuration_sha256"] {
		return ExportReport{}, ErrInvalid
	}
	installation, e := read("/var/lib/aster-cloud-installer/controller/state.json", 1<<20)
	if e != nil || digestBytes(installation) != p.Identity["installation_sha256"] {
		return ExportReport{}, ErrInvalid
	}
	var loaded control.Config
	if !strictRecord(configRaw, &loaded) {
		return ExportReport{}, ErrInvalid
	}
	a, _ = json.Marshal(config)
	b, _ = json.Marshal(loaded)
	if !bytes.Equal(a, b) {
		return ExportReport{}, ErrInvalid
	}
	// All references originate in the validated config. An export-intent path
	// can never widen this allowlist to arbitrary host files.
	type reference struct {
		label, path string
		private     bool
		maximum     int64
	}
	refs := []reference{{"dsn_file", config.DSNFile, true, 4096}, {"tls_cert_file", config.TLSCertFile, false, 65536}, {"tls_key_file", config.TLSKeyFile, true, 65536},
		{"billing_token_file", config.BillingTokenFile, true, 4096}, {"admin_read_token_file", config.AdminReadTokenFile, true, 4096}, {"admin_write_token_file", config.AdminWriteTokenFile, true, 4096}}
	for _, node := range config.Nodes {
		refs = append(refs, reference{node.ID + ":ca_file", node.CAFile, false, 1 << 20}, reference{node.ID + ":client_cert_file", node.ClientCertFile, false, 1 << 20}, reference{node.ID + ":client_key_file", node.ClientKeyFile, true, 1 << 20})
	}
	sort.Slice(refs, func(i, j int) bool { return refs[i].label < refs[j].label })
	if len(intent.Materials) != len(refs) {
		return ExportReport{}, ErrInvalid
	}
	files := map[string][]byte{"controller/config.json": configRaw, "source/installation.json": installation, "source/plan.json": plan, "source/isolated.json": isolated}
	var dsn []byte
	for i, ref := range refs {
		raw, e := control.ReadProtected(ref.path, ref.private, ref.maximum)
		m := intent.Materials[i]
		if e != nil || m.Label != ref.label || m.Path != ref.path || m.SHA256 != digestBytes(raw) {
			return ExportReport{}, ErrInvalid
		}
		files["materials/"+m.SHA256+".bin"] = raw
		if ref.label == "dsn_file" {
			dsn = raw
		}
	}
	files["controller/materials.json"], e = json.Marshal(intent.Materials)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	// Never reuse a partial output/key. The persistent export-started seal is
	// intentionally retained on ALL failures; local resume remains prohibited.
	for _, name := range []string{"recovery.key", "backup.age", "exported.json"} {
		if _, e := os.Lstat(filepath.Join(dir, name)); !os.IsNotExist(e) {
			return ExportReport{}, ErrInvalid
		}
	}
	scratch, e := os.MkdirTemp(dir, ".export-")
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	defer os.RemoveAll(scratch) // exactly the private directory created above
	left := MaxDataBytes
	entries := []Entry{}
	paths := map[string]string{}
	write := func(name string, emit func(io.Writer) error) error {
		f, e := os.CreateTemp(scratch, "entry-")
		if e != nil {
			return ErrInvalid
		}
		defer f.Close()
		h := sha256.New()
		before := left
		if emit(quotaWriter{io.MultiWriter(f, h), &left}) != nil || f.Sync() != nil {
			return ErrInvalid
		}
		entries = append(entries, Entry{Name: name, Size: before - left, SHA256: hex.EncodeToString(h.Sum(nil))})
		paths[name] = f.Name()
		return nil
	}
	for name, raw := range files {
		if write(name, func(w io.Writer) error { _, e := w.Write(raw); return e }) != nil {
			return ExportReport{}, ErrInvalid
		}
	}
	store, e := control.OpenDSN(strings.TrimSpace(string(dsn)))
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	defer store.DB.Close()
	if store.Check(ctx) != nil {
		return ExportReport{}, ErrInvalid
	}
	rows, e := SnapshotDatabase(ctx, store.DB, write)
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	manifest := Manifest{Schema: 1, Protocol: Protocol, ControllerID: config.ControllerID, OperationID: operation, SourceCommit: p.Identity["source_commit"], SchemaVersion: len(migrations.All()), SourcePlanSHA256: marker.PlanSHA256, Files: entries}
	if _, ok := validManifest(manifest, config.ControllerID, operation); !ok {
		return ExportReport{}, ErrInvalid
	}
	raw, e := json.Marshal(manifest)
	if e != nil || len(raw) > int(MaxManifestBytes) {
		return ExportReport{}, ErrInvalid
	}
	key := make([]byte, 32)
	if _, e = rand.Read(key); e != nil {
		return ExportReport{}, ErrInvalid
	}
	recovery := KeyPrefix + hex.EncodeToString(key)
	clear(key)
	if e = writePrivateNew(filepath.Join(dir, "recovery.key"), []byte(recovery+"\n")); e != nil {
		return ExportReport{}, ErrInvalid
	}
	output, e := os.CreateTemp(scratch, "encrypted-")
	if e != nil {
		return ExportReport{}, ErrInvalid
	}
	defer output.Close()
	if e = encryptContainer(output, recovery, raw, entries, paths); e != nil || output.Sync() != nil {
		return ExportReport{}, ErrInvalid
	}
	info, e := output.Stat()
	if e != nil || info.Size() > MaxCipherBytes {
		return ExportReport{}, ErrInvalid
	}
	if _, e = output.Seek(0, 0); e != nil {
		return ExportReport{}, ErrInvalid
	}
	h := sha256.New()
	if _, e = io.Copy(h, output); e != nil {
		return ExportReport{}, ErrInvalid
	}
	if e = publishNew(output.Name(), filepath.Join(dir, "backup.age")); e != nil {
		return ExportReport{}, ErrInvalid
	}
	return ExportReport{Schema: 1, ControllerID: config.ControllerID, OperationID: operation, ArchiveSHA256: hex.EncodeToString(h.Sum(nil)), ArchiveBytes: info.Size(), DatabaseRows: rows, SourceReadOnly: true}, nil
}

func writePrivateNew(path string, raw []byte) error {
	f, e := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if e != nil {
		return ErrInvalid
	}
	defer f.Close()
	if _, e = f.Write(raw); e != nil || f.Sync() != nil {
		return ErrInvalid
	}
	d, e := os.Open(filepath.Dir(path))
	if e != nil {
		return ErrInvalid
	}
	defer d.Close()
	return d.Sync()
}

func encryptContainer(output io.Writer, key string, manifest []byte, entries []Entry, paths map[string]string) error {
	writer, e := encryptWriter(output, key)
	if e != nil {
		return ErrInvalid
	}
	tw := tar.NewWriter(writer)
	write := func(name string, size int64, source io.Reader) error {
		if tw.WriteHeader(&tar.Header{Name: name, Mode: 0600, Size: size, Typeflag: tar.TypeReg, Format: tar.FormatUSTAR}) != nil {
			return ErrInvalid
		}
		n, e := io.Copy(tw, source)
		if e != nil || n != size {
			return ErrInvalid
		}
		return nil
	}
	if write("manifest.json", int64(len(manifest)), bytes.NewReader(manifest)) != nil {
		return ErrInvalid
	}
	for _, entry := range entries {
		f, e := os.Open(paths[entry.Name])
		if e != nil {
			return ErrInvalid
		}
		e = write(entry.Name, entry.Size, f)
		f.Close()
		if e != nil {
			return ErrInvalid
		}
	}
	if tw.Close() != nil || writer.Close() != nil {
		return ErrInvalid
	}
	return nil
}
